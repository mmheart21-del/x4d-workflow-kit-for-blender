"""Decode our generated RGBA PNG assets without touching bpy.data.
Icons generated by scripts/build_icons.py use filter 0, RGBA8, no interlace.
Keeping this reader deliberately limited makes malformed assets fail clearly.
"""
import struct,zlib

def read_rgba(path):
    data=open(path,'rb').read()
    if data[:8]!=b'\x89PNG\r\n\x1a\n':raise ValueError('Not a PNG: '+path)
    offset=8;compressed=[];width=height=0
    while offset<len(data):
        length=struct.unpack_from('>I',data,offset)[0];kind=data[offset+4:offset+8];payload=data[offset+8:offset+8+length];offset+=12+length
        if kind==b'IHDR':
            width,height,depth,color,compression,filter_method,interlace=struct.unpack('>IIBBBBB',payload)
            if (depth,color,compression,filter_method,interlace)!=(8,6,0,0,0):raise ValueError('Unsupported icon PNG encoding: '+path)
            if width>256 or height>256:raise ValueError('Icon dimensions too large')
        elif kind==b'IDAT':compressed.append(payload)
        elif kind==b'IEND':break
    pixels=zlib.decompress(b''.join(compressed));stride=width*4+1
    if not width or len(pixels)!=stride*height:raise ValueError('Invalid icon pixel data: '+path)
    rows=[]
    for y in range(height):
        row=pixels[y*stride:(y+1)*stride]
        if row[0]!=0:raise ValueError('Regenerate icons with scripts/build_icons.py: '+path)
        rows.append(row[1:])
    # Blender previews use bottom-to-top pixels.
    return width,height,[v/255.0 for row in reversed(rows) for v in row]
